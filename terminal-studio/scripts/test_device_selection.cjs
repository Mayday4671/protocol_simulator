const assert=require('node:assert/strict');
const fs=require('node:fs'),ts=require('typescript'),Module=require('node:module'),path=require('node:path');
const file=path.resolve('src/lib/deviceSelection.ts'),mod=new Module(file,module);
mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,file);
const {deviceFieldValue,deviceSelectionValues}=mod.exports;
const field=(name,role,profile_key,enc='hex',len=2)=>({name,role,profile_key,enc,len,value:''});
const src=field('主叫','src_id'),dst=field('被叫','dst_id'),serial=field('资产编号','device_sn','serial'),rate=field('采集频率','none','rate'),session=field('凭据','session','session');
const fields=[src,dst,serial,rate,session,field('终端','none')];
const device={id:1,name:'甲',address:'000A',properties:{serial:'1234',rate:'20',session:'ffff'},fields:[serial,{...rate,enc:'uint'},session]};
assert.equal(deviceFieldValue(src,device),'000A');
assert.equal(deviceFieldValue(serial,device),'1234');
assert.deepEqual(deviceSelectionValues(src,device,fields),{'主叫':'000A','资产编号':'1234','采集频率':'0014'});
assert.deepEqual(deviceSelectionValues(dst,device,fields),{'被叫':'000A'},'Target selection must not change sender or its properties/session');
assert.deepEqual(deviceSelectionValues(serial,device,fields),{'资产编号':'1234','采集频率':'0014'},'Payload selection never overwrites a different identity');
assert.throws(()=>deviceFieldValue(field('设备','none'),device),/未配置/,'Never infer behavior from display name');
assert.throws(()=>deviceFieldValue({...src,len:1},{...device,address:'1234'}),/超过/);
assert.throws(()=>deviceSelectionValues(src,{...device,properties:{...device.properties,rate:'65536'}},fields),/采集频率/);
assert.throws(()=>deviceSelectionValues(src,{...device,fields:[]},fields),/定义不存在/);
assert.equal(deviceSelectionValues(src,{...device,properties:{serial:'1234'}},fields)['采集频率'],'','Missing properties clear previous device data');
assert.equal(deviceFieldValue({...src,enc:'uint'},device),'10');
console.log('PASS field-local identity, explicit property mappings, encoding conversion, missing values, width checks and source/target separation');
